export const getStoredBookings = () => {
  try {
    const dataStr = localStorage.getItem("hleven_admin_bookings");
    if (dataStr) return JSON.parse(dataStr);
  } catch (e) {
    console.error("Error loading bookings from localStorage", e);
  }
  localStorage.setItem("hleven_admin_bookings", JSON.stringify(INITIAL_BOOKINGS));
  return INITIAL_BOOKINGS;
};

